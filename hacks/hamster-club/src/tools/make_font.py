# code for each new glyph: a-z at 0x01-0x1A, then punctuation
NEW = {c: 0x01 + i for i, c in enumerate("abcdefghijklmnopqrstuvwxyz")}
NEW.update({".": 0x1B, ",": 0x1C, "-": 0x1D, '"': 0x1E, ";": 0x1F, "+": 0x20})

# glyphs the game already has, as they should be typed in script "en" fields
KEEP = {" ": 0x00, "!": 0x7B, "?": 0x7C, "'": 0x99, "/": 0x9B, "%": 0x9C, ":": 0x9F,
        "…": 0xA1, "&": 0xA2, "♂": 0xA4, "♀": 0xA5, "(": 0xAF, ")": 0xB0, "~": 0x79,
        "♡": 0xE3, "▼": 0xB7, "▲": 0xB8, "▶": 0xB9, "◀": 0xBA}
KEEP.update({chr(ord("A") + i): 0x7F + i for i in range(26)})
KEEP.update({str(i): 0x6F + i for i in range(10)})


def main():
    rom = open("rom/original.gbc", "rb").read()
    sheet = gfx.rip(rom, FONT_OFF, FONT_COUNT, "2bpp_gb", 16)
    os.makedirs("gfx/orig", exist_ok=True)
    os.makedirs("gfx/edit", exist_ok=True)
    sheet.save("gfx/orig/font.png")
    px = sheet.load()
    for ch, code in NEW.items():
        x0, y0 = (code % 16) * 8, (code // 16) * 8
        for y, row in enumerate(GLYPHS[ch]):
            for x, c in enumerate(row):
                px[x0 + x, y0 + y] = 3 if c == "#" else 0
    # tiles D7-DA spell ケージ in the cage name-entry title (notes/rom.md); copy
    # C a g e over them so the title reads "Cage name?"
    for dst, ch in zip(range(0xD7, 0xDB), "Cage"):
        src = KEEP.get(ch, NEW.get(ch))
        for y in range(8):
            for x in range(8):
                px[(dst % 16) * 8 + x, (dst // 16) * 8 + y] = px[(src % 16) * 8 + x, (src // 16) * 8 + y]
    sheet.save("gfx/edit/font.png")
    lines = ["; Hamster Club English insert table. Generated by tools/make_font.py",
             "; ' and \" are straight quotes; … is one tile"]
    for ch, code in sorted({**KEEP, **NEW}.items(), key=lambda kv: kv[1]):
        lines.append(f"{code:02X}={ch}")
    lines += ["*EF=<br>", "$F0=<wait>,0", "$EE=<clr>,0", "$F2=<name>,1"]
    with open("tables/en.tbl", "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"font: {len(NEW)} new glyphs; en.tbl: {len(KEEP) + len(NEW)} characters")


if __name__ == "__main__":
    main()
