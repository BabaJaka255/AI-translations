"""Generate tables/jp.tbl for Hamster Club (GBC). Font is at ROM 0xFE250, 16 bytes/glyph,
glyph index == text byte. Dakuten (7E) and handakuten (7D) follow the base kana as a
separate byte; the table maps the pairs to precomposed kana."""
import sys

hira = "あいうえおかきくけこさしすせそたちつてとなにぬねのはひふへほまみむめもやゆよらりるれろわをん"
small_h = "ぁぃぅぇぉゃゅょっ"
kata = "アイウエオカキクケコサシスセソタチツテトナニヌネノハヒフホマミムメモヤユヨラリルレロワヲン"  # no ヘ: game reuses へ
small_k = "ァィゥェォャュョッ"
single = {}
for i, c in enumerate(hira): single[0x01 + i] = c
for i, c in enumerate(small_h): single[0x2F + i] = c
for i, c in enumerate(kata): single[0x38 + i] = c
for i, c in enumerate(small_k): single[0x65 + i] = c
single[0x6E] = "ヶ"
single[0x6F] = "0"
for i in range(9): single[0x70 + i] = str(i + 1)
for i, c in enumerate("〜ー！？"): single[0x79 + i] = c
single[0x7D] = "゜"
single[0x7E] = "゛"
for i in range(26): single[0x7F + i] = chr(ord("A") + i)
for i, c in enumerate("’，／％。、：・…＆＊♂♀"): single[0x99 + i] = c
for b, c in {0xB1: "『", 0xB2: "』", 0xB3: "「", 0xB4: "」", 0xB5: "【", 0xB6: "】"}.items():
    single[b] = c  # corner brackets around emphasized words; 【】 on the keyboard
for i, c in enumerate("▼▲▶◀"): single[0xB7 + i] = c
for i, c in enumerate("父母．♡？上下左右走"): single[0xE0 + i] = c

dak = dict(zip("かきくけこさしすせそたちつてとはひふへほカキクケコサシスセソタチツテトハヒフホウ",
               "がぎぐげござじずぜぞだぢづでどばびぶべぼガギグゲゴザジズゼゾダヂヅデドバビブボヴ"))
han = dict(zip("はひふへほハヒフホ", "ぱぴぷぺぽパピプポ"))
inv = {c: b for b, c in single.items()}
lines = ["; Hamster Club (GBC) Japanese table. Generated by tools/make_jp_tbl.py",
         "; control codes: see notes/rom.md"]
for base, comp in dak.items():
    lines.append(f"{inv[base]:02X}7E={comp}")
for base, comp in han.items():
    lines.append(f"{inv[base]:02X}7D={comp}")
for b in sorted(single):
    lines.append(f"{b:02X}={single[b]}")
lines += ["00=　", "*EF=<br>", "$F0=<wait>,0", "$EE=<clr>,0", "$F2=<name>,1"]
open(sys.argv[1], "w", encoding="utf-8").write("\n".join(lines) + "\n")
