# code layout: digits 00-09 and the '*' at 0A are the game's own; FE is space.
ORDER = ("ABCDEFGHIJKLMNOPQRSTUVWXYZ" "abcdefghijklmnopqrstuvwxyz" ".,!?'\"-:/()&…~≤+")
FREE = [c for c in range(0x0B, 0x60) if c not in (0x1A, 0x2A)]
CODES = {ch: FREE[i] for i, ch in enumerate(ORDER)}
assert len(ORDER) <= len(FREE)


def tile(rows):
    lo = bytearray(8); hi = bytearray(8)
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == "#":
                lo[y] |= 0x80 >> x; hi[y] |= 0x80 >> x
    return bytes(lo + hi)


def table():
    t = {i: str(i) for i in range(10)}
    t.update({v: k for k, v in CODES.items()})
    return t


def apply(rom, chr_page_off):
    """Write glyphs over the kana tiles at file offset chr_page_off (tile 0 of the font page)."""
    for ch, code in CODES.items():
        o = chr_page_off + code * 16
        rom[o:o + 16] = tile(G[ch])
    # blank every other kana tile so leftover Japanese shows up as gaps in testing
    for code in range(0x0B, 0x60):
        if code not in CODES.values():
            rom[chr_page_off + code * 16: chr_page_off + code * 16 + 16] = bytes(16)
