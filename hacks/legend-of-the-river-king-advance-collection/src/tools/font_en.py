def width(ch):
    if ch == ' ':
        return 3
    rows = G[ch]
    return max(len(r.rstrip()) for r in rows) + 1


def tile(ch, ink=3, bg=1):
    """32-byte 4bpp tile (font cell), art starting at row 1, column 0."""
    rows = [''] + list(G.get(ch, ())) if ch != ' ' else ['']
    out = bytearray()
    for y in range(8):
        r = rows[y] if y < len(rows) else ''
        px = [ink if x < len(r) and r[x] == '#' else bg for x in range(8)]
        for x in range(0, 8, 2):
            out.append(px[x] | px[x + 1] << 4)
    return bytes(out)
