def _d(x): return x
PARAM={0xf8,0xf9,0xfb,0xfc,0xfd}
def dec(raw,game):
    out='';i=0
    while i<len(raw):
        b=raw[i]
        if b>=0xf0:
            if b in PARAM and i+1<len(raw): out+='{%02x %02x}'%(b,raw[i+1]); i+=2
            else: out+='{%02x}'%b; i+=1
            continue
        if b in (0x8d,0x8e) and out:
            comb='゙' if b==0x8d else '゚'
            n=unicodedata.normalize('NFC',out[-1]+comb)
            if len(n)==1: out=out[:-1]+n
            else: out+=('゛' if b==0x8d else '゜')
            i+=1; continue
        c=BASE.get(b) if b<0x8d else None
        if c is None: c=SYM[game].get(b,'[%02x]'%b)
        out+=c; i+=1
    return out
