"""Generate subdata.c for the JP subtitle hack: English .GSC scripts from PAL EFF/SUBTITLE.NCB,
eu_font (PSMT4 256x256 as CT32 64x128) + CT16 CLUT from PAL system.r, kerning table from the PAL ELF."""
import sys, os, struct, re
G = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
sys.path.insert(0, os.path.join(G, 'tools'))
import b7_lz, b7_ncb, b7_strings, b7_font
import json

def carr(name, b, typ='unsigned char', align=16):
    s = f'const {typ} {name}[{len(b)}] __attribute__((aligned({align}))) = {{\n'
    for i in range(0, len(b), 32):
        s += ','.join(str(x) for x in b[i:i+32]) + ',\n'
    return s + '};\n'

def jp_tut_ids(jp, jt, n):
    """Message id of each case in the JP tutorial builder's jump table (0x22fb40)."""
    off = lambda v: v - 0x200000 + 0x1000
    ids = []
    for i in range(n):
        t = struct.unpack_from('<I', jp, off(jt + 4 * i))[0]
        w0, w1 = struct.unpack_from('<II', jp, off(t))
        if w1 >> 16 in (0x2403, 0x2408):          # addiu v1/t0, zero, id
            ids.append(w1 & 0xffff)
        elif w0 == 0x2410015c and w1 >> 16 == 0x2407:  # case 0: id stored from $zero
            ids.append(0)
        else:
            ids.append(-1)                          # record without an id (never shown)
    return ids

def wrap(text, width=31, maxlines=5):
    """Re-break a PAL message ('$/' = line break) into at most maxlines lines of <= width chars."""
    lines = text.split('$/')
    clen = lambda t: len(re.sub(r'\$\d', 'XX', t))
    if len(lines) <= maxlines and all(clen(l) <= width for l in lines):
        return lines
    words = '\u3000'.join(lines).split('\u3000'); out = ['']
    for w in words:
        cand = (out[-1] + '\u3000' + w) if out[-1] else w
        if clen(cand) <= width: out[-1] = cand
        else: out.append(w)
    assert len(out) <= maxlines, out
    return out

def tutorial(jp, pal):
    off = lambda v: v - 0x200000 + 0x1000
    def s(v):
        o = off(v); return pal[o:pal.index(b'\0', o)].decode('cp932')
    c = ''
    for name, jt, n, base, pn in (('goku', 0x4c0000 - 0xb40, 0x54, 0x402878, 0x51),
                                  ('yuri', 0x4c0000 - 0x9f0, 0x4d, 0x402d88, 0x44)):
        msgs = {}
        for i in range(pn):
            idv, en = struct.unpack_from('<2I', pal, off(base + 16 * i))
            msgs.setdefault(idv, s(en))
        ids = jp_tut_ids(jp, jt, n)
        c += f'const int tut_{name}_n = {n};\nconst struct tut tut_{name}[] = {{\n'
        for idv in ids:
            lines = wrap(msgs[idv]) if idv >= 0 else ['']
            enc = '$/'.join(lines).encode('cp932')
            c += f'{{{idv}, "' + ''.join(f'\\x{b:02x}' for b in enc) + '"},\n'
        c += '};\n'
    return 'struct tut { int id; const char *text; };\n' + c

def cstr(b):
    return '"' + ''.join(f'\\x{x:02x}' for x in b) + '"'

def strpool(slots):
    c = ''
    for va, b in sorted(slots.items()):
        c += f'const char sp_{va:x}[] = {cstr(b)};\n'
    return c

def main(font_rh2, out):
    ncb = open(os.path.join(G, 'rom/pal/EFF/SUBTITLE.NCB'), 'rb').read()
    E = b7_ncb.entries(ncb); offs = sorted(o for _, o, _ in E) + [len(ncb)]
    subs = {}
    for n, o, _ in E:
        if n.endswith('.GSC'):
            subs[n[:-4]] = b7_lz.decompress(ncb[o:offs[offs.index(o) + 1]])
    f = open(font_rh2, 'rb').read()
    clut = f[0x1b0:0x1d0]
    img = b''.join(f[a:a + 0x2000] for a in (0x230, 0x2290, 0x42f0, 0x6350))
    assert len(img) == 0x8000
    pal = open(os.path.join(G, 'rom/pal/SLES_501.09'), 'rb').read()
    o = 0x43e410 - 0x200000 + 0x1000; kern = pal[o:o + 0xc0]
    c = '/* generated by gen_data.py */\n'
    c += carr('kern', kern, align=4)
    keys = sorted(subs)
    for k in keys:
        c += carr('s_' + k, subs[k], align=4)
    c += 'struct sub { char key[8]; const unsigned char *data; };\n'
    c += f'const int sub_count = {len(keys)};\nconst struct sub sub_index[] = {{\n'
    c += ''.join(f'{{"{k}", s_{k}}},\n' for k in keys) + '};\n'
    jp = open(os.path.join(G, 'rom/jp/SLPM_650.08'), 'rb').read()
    c += tutorial(jp, pal)
    # in-game font: eu_font LZ-packed for the kanji1 install buffer; PAL in-game kerning + 0x81xx punctuation map
    lz = b7_lz.compress(b7_font.with_buttons(f))
    c += carr('eufont_lz', lz) + f'const int eufont_lz_size = {len(lz)};\n'
    o = 0x43e210 - 0x200000 + 0x1000; c += carr('ui_kern', pal[o:o + 0x200], align=4)
    o = 0x43e611 - 0x200000 + 0x1000; n = 0
    while pal[o + 2 * n]: n += 1
    c += carr('ui_punct', pal[o:o + 2 * n + 1], align=4)
    placed, where, rest, _ = b7_strings.allocate(jp, pal)
    c += strpool(rest)
    json.dump({'placed': {f'{k:x}': v.hex() for k, v in placed.items()}, 'slots': {f'{k:x}': f'{v:x}' for k, v in where.items()}},
              open(os.path.join(os.path.dirname(out), 'strings.json'), 'w'), indent=0)
    open(out, 'w').write(c)
    print(len(where) + len(rest), 'text slots:', len(placed), 'strings in freed JP space,', len(set(rest.values())), 'in the segment')
    print(len(keys), 'scripts,', sum(len(v) for v in subs.values()), 'bytes')

if __name__ == '__main__':
    main(*sys.argv[1:3])
