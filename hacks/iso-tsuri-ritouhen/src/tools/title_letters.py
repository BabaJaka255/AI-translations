def block_rows(txt, gap=2):
    rows = [''] * 10
    for i, ch in enumerate(txt):
        for y in range(10): rows[y] += L[ch][y] + ('.' * gap if i < len(txt) - 1 else '')
    return rows
def place(out, txt, x, y, gap=2):
    """out: dict (x,y)->colour; yellow body (2) with 1px black outline (1)."""
    rows = block_rows(txt, gap)
    body = {(x + i, y + j) for j, r in enumerate(rows) for i, c in enumerate(r) if c == '#'}
    for (px, py) in body:
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                q = (px + dx, py + dy)
                if q not in body and q not in out: out[q] = 1
    for p in body: out[p] = 2
    return len(rows[0])
