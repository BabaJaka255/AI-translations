def word(txt, x, y, kern=None, scale=1.0, slant=0.16):
    out = []
    for i, ch in enumerate(txt):
        adv, strokes = G[ch]
        for s in strokes:
            out.append([(x + (p[0] + (40 - p[1]) * slant) * scale, y + p[1] * scale, p[2] * scale) + tuple(p[3:]) for p in s])
        x += adv * scale + (kern[i] if kern else 0)
    return out, x

