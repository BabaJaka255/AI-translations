"""Write script/script.tsv (one row per string or table entry) from script/strings.json + tables.json.

Columns: id, location, japanese, english, limit, notes. Edit the JSON, not the TSV; the TSV is for reading and
diffing. python3 tools/export_tsv.py
"""
import csv, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); GAME = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from inventory import STRINGS, TABLES
S = json.load(open(os.path.join(GAME, 'script', 'strings.json'), encoding='utf-8'))
T = json.load(open(os.path.join(GAME, 'script', 'tables.json'), encoding='utf-8'))
LIMIT = {'intro': 'crawl lines wrapped at 224 px (bold proportional font)', 'ending': 'crawl lines wrapped at 224 px (bold proportional font)',
         'name_entry': 'generated by script_en.keyboard()'}
with open(os.path.join(GAME, 'script', 'script.tsv'), 'w', encoding='utf-8', newline='') as f:
    w = csv.writer(f, delimiter='\t', lineterminator='\n')
    w.writerow(['id', 'location', 'japanese', 'english', 'limit', 'notes'])
    for k, v in S.items():
        if k not in STRINGS: continue
        addr, ptrs, _ = STRINGS[k]
        loc = '$C1:%04X; pointer operands %s' % (addr, ', '.join('ROM %05X' % p for p in ptrs))
        w.writerow([k, loc, v.get('jp', '').replace('\n', '\\n'), v.get('en', '').replace('\n', '\\n'),
                    LIMIT.get(k, 'screen layout: ] = newline, ^ = cursor stop'), v.get('notes', '')])
    for k, t in T.items():
        base, count, stride, cols, notes = TABLES[k]
        for e in t['entries']:
            w.writerow(['%s[%d]' % (k, e['i']), '$C1:%04X + %d * %d' % (base, e['i'], stride), e['jp'], e['en'],
                        '%d columns' % t.get('columns', cols), t.get('notes', notes)])
print('script.tsv written')
