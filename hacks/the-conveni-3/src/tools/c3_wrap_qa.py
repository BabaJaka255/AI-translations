"""Rewrap the Conveni Encyclopedia answers (ELF 0x42E000-0x431000, ids 818-964) to the answer box.

  C3_ELF=<built ELF> python3 tools/c3_wrap_qa.py [--width 370] [--lines 7]

The answer box is tall (7 lines, ~390 px of the talk font) and has NO mid-text wait: tested 2026-11-03,
"/kB" mid-text freezes the answer and "/s00" prints the owner's name. Each answer is rewrapped to --width;
the tool reports nothing over --lines because every answer fits.
A line never starts with a digit ("/n1" would be read as a code), so the word before it moves down too. Output: script/tr/elf_024_qa_pages.tsv (merged after the answers).
Reads the unpaged English from script/tr/elf_006.tsv & co. through script/elf.json minus this file's own output,
so delete elf_024 and re-merge before running it again.
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import c3_tr as T  # noqa: E402
from c3font import idx, table  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("--width", type=int, default=370)
ap.add_argument("--lines", type=int, default=7)
ap.add_argument("--sep", default="/n")
ap.add_argument("--test", action="store_true", help="818/820/822 get three different separators")
a = ap.parse_args()
elf = open(T.ELF_PATH, "rb").read()
t, nt = table(elf, "talk"), table(elf, "name")


def w(code):
    e = t[idx(code)] if 0 <= idx(code) < len(t) else (0xFF,)
    if e[0] == 0xFF and 0 <= idx(code) < len(nt):
        e = nt[idx(code)]
    return e[3] if e[0] != 0xFF else 18


out, over = [], 0
for e in T.load("elf")["entries"]:
    o = int(e["offset"], 16)
    if not (0x42E000 <= o < 0x431000) or e["jp"].count("/n") < 2 or not e["en"]:
        continue
    text = re.sub(r"/kB/n|/kB/p|/w045/kB/s00/p|/n", " ", e["en"]).replace("  ", " ").strip()
    lines, cur = [], ""
    for wd in text.split(" "):
        trial = f"{cur} {wd}" if cur else wd
        if cur and T._width(trial, w) > a.width:
            if wd[:1].isdigit() and " " in cur:  # "/n" + digit misparses: carry the previous word down
                cur, prev = cur.rsplit(" ", 1)
                wd = f"{prev} {wd}"
            lines.append(cur)
            cur = wd
        else:
            cur = trial
    lines.append(cur)
    sep = a.sep
    if a.test:
        sep = {818: "/kB/n", 820: "/w045/kB/s00/p", 822: "/kB/p"}.get(e["id"], sep)
    pages = ["/n".join(lines[i:i + a.lines]) for i in range(0, len(lines), a.lines)]
    out.append(f"{e['id']}\t{sep.join(pages)}")
path = os.path.join(HERE, "..", "script", "tr", "elf_024_qa_pages.tsv")
open(path, "w", encoding="utf-8").write(
    f"# generated by tools/c3_wrap_qa.py --width {a.width} --lines {a.lines} --sep {a.sep}\n" + "\n".join(out) + "\n")
print(len(out), "answers")
