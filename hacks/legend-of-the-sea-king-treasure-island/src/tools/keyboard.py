"""Write text/en_kbd.txt: the English name-entry keyboard (display rows and key tables).
Key tables hold one-letter words 0x1Fcc; the engine's name_add joins two letters into one word (0xHHLL)."""
ROWS = ['ABCDEFGHIJ', 'KLMNOPQRST', "UVWXYZ.,'-", 'abcdefghij', 'klmnopqrst']
KROWS = ['uvwxyz!?&~', '0123456789', '()/:;+*=#%', '_         ', '          ', '          ']
def row(keys):
    return ''.join('{>%d}%s' % (12 + 24 * k, c) for k, c in enumerate(keys) if c != ' ')
def word(c):
    return '{#%04x}' % (0x1f20 if c in ' _' else 0x1f00 | ord(c))
out = ['# Name entry keyboard (generated by tools/keyboard.py)',
       "63|{A}'s name, please.", '78|']
for k, r in enumerate(ROWS): out.append('%d|%s' % (79 + k, row(r)))
krows = '{E}'.join(row(r) for r in KROWS)
out += ['64|' + krows, '66|' + krows]
table = '{#0000}' + ''.join(word(c) for r in ROWS + KROWS for c in r)
out += ['84|' + table, '85|' + table]
# secret name ("ふね太郎" -> Funetaro, typed as 4 letter pairs)
pairs = ['Fu', 'ne', 'ta', 'ro']
out.append('86|{#0000}' + ''.join('{#%02x%02x}' % (ord(b), ord(a)) for a, b in pairs))
# Message keyboard (0x80088ac4): page A shows rows 79-83 + table 101, page B rows 91-95 + table 102,
# page C rows 96-100 + table 103. Rows 91-100 are drawn 8 px further right than 79-83.
BROWS = ['uvwxyz!?&~', '0123456789', '()/:;+*=#%', '"$@<>[]^_|', "'-.,`     "]
CROWS = ['abcdefghij', 'klmnopqrst', 'uvwxyz.,!?', '0123456789', "'-&()/:;%+"]
def row2(keys):
    return ''.join('{>%d}%s' % (4 + 24 * k, c) for k, c in enumerate(keys) if c != ' ')
DIGITS = '{>48}{#0017}' + ''.join('{>%d}{#%04x}' % (72 + 16 * k, 8 + k) for k in range(10))
out += ['87|Sym' + DIGITS, '88|abc' + DIGITS, '89|ABC' + DIGITS,
        '90|{#0006}{>24}{#0007}{>48}{#0001}{>72}{#0002}{>88}{#001c}{>104}{#001b}{>120}{#001a}{>136}Line{>176}OK',
        '122|Please keep it to 3 lines.']
for k, r in enumerate(BROWS): out.append('%d|%s' % (91 + k, row2(r)))
for k, r in enumerate(CROWS): out.append('%d|%s' % (96 + k, row2(r)))
def mword(c): return '{#%04x}' % (0x1f20 if c == ' ' else 0x1f00 | ord(c))
out += ['101|' + ''.join(mword(c) for r in ROWS for c in r),
        '102|{#0000}' + ''.join(mword(c) for r in BROWS for c in r),
        '103|{#0000}' + ''.join(mword(c) for r in CROWS for c in r)]
open('text/en_kbd.txt', 'w').write('\n'.join(out) + '\n')
